function jar() {
  const map = new Map();
  return {
    capture(res) {
      for (const c of res.headers.getSetCookie()) {
        const [pair] = c.split(";");
        const eq = pair.indexOf("=");
        if (eq > 0) map.set(pair.slice(0, eq).trim(), pair.slice(eq + 1).trim());
      }
    },
    header() {
      return [...map.entries()].map(([k, v]) => `${k}=${v}`).join("; ");
    },
    csrf() {
      return map.get("pulseid_csrf") || "";
    },
  };
}

async function http(method, apiPath, { jar: cookieJar, body, form, ip: xff } = {}) {
  const headers = {};
  if (cookieJar?.header()) headers.cookie = cookieJar.header();
  headers["x-forwarded-for"] = xff || nextIp();
  if (form) {
    /* boundary set by fetch */
  } else if (body !== undefined) {
    headers["content-type"] = "application/json";
  }
  if (method !== "GET" && cookieJar?.csrf()) headers["x-csrf-token"] = cookieJar.csrf();
  const res = await fetch(`${BASE}${apiPath}`, {
    method,
    headers,
    body: form ?? (body !== undefined ? JSON.stringify(body) : undefined),
  });
  cookieJar?.capture(res);
  return { status: res.status, data: await res.json().catch(() => null) };
}

const db = new Database(DB_PATH, { readonly: false });
db.pragma("journal_mode = WAL");

function sleep(ms) {
  return new Promise((r) => setTimeout(r, ms));
}

async function waitForIndexing(registrationId, expectedMinimum, timeoutMs = 90_000) {
  const t0 = Date.now();
  while (Date.now() - t0 < timeoutMs) {
    const n = db
      .prepare("SELECT COUNT(*) AS n FROM rag_chunks WHERE registration_id = ?")
      .get(registrationId).n;
    if (n >= expectedMinimum) return n;
    await sleep(1500);
  }
  return db.prepare("SELECT COUNT(*) AS n FROM rag_chunks WHERE registration_id = ?").get(registrationId).n;
}

