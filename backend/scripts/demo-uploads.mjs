function generateTextPdf(filePath, title, patientName, sections) {
  return new Promise((resolve, reject) => {
    const doc = new PDFDocument({ size: "A4", margin: 56 });
    const stream = fs.createWriteStream(filePath);
    doc.pipe(stream);
    doc.fontSize(16).font("Helvetica-Bold").fillColor("#111").text(title);
    doc.moveDown(0.3);
    doc.fontSize(10).fillColor("#444").text(`Patient: ${patientName}`);
    doc.text(`Generated: ${new Date().toISOString().slice(0, 10)}`);
    doc.moveDown(0.8);
    for (const [heading, body] of sections) {
      doc.fontSize(11).font("Helvetica-Bold").fillColor("#0E7C7B").text(heading);
      doc.moveDown(0.2);
      doc.fontSize(10).font("Helvetica").fillColor("#222").text(body, { lineGap: 2 });
      doc.moveDown(0.6);
    }
    doc.fontSize(8).fillColor("#888").text("Demo document generated by scripts/demo-uploads.mjs — synthetic data only.");
    doc.end();
    stream.on("finish", resolve);
    stream.on("error", reject);
  });
}

async function generateScanImage(filePath, title, patientName, format /* png | jpeg */) {
  const width = 620;
  const height = 860;
  const esc = (s) => s.replace(/&/g, "&amp;").replace(/</g, "&lt;");
  const rows = [
    { size: 22, weight: "bold", text: title, y: 60 },
    { size: 13, weight: "normal", text: `Patient: ${esc(patientName)}`, y: 110 },
    { size: 13, weight: "normal", text: `Date: ${new Date().toISOString().slice(0, 10)}`, y: 134 },
    { size: 13, weight: "normal", text: "Ref: DEMO-SCAN-" + crypto.randomInt(100000, 999999), y: 158 },
    { size: 12, weight: "normal", text: "— Image reports are stored verbatim in PulseID —", y: 800 },
    { size: 12, weight: "normal", text: "   they are viewable/downloadable, not text-indexed (no OCR).", y: 822 },
  ];
  const svg = `<svg width="${width}" height="${height}" xmlns="http://www.w3.org/2000/svg">
    <rect width="100%" height="100%" fill="#fdfcf7"/>
    <rect x="24" y="24" width="${width - 48}" height="${height - 48}" fill="none" stroke="#9aa5a4" stroke-width="2"/>
    ${rows.map((r) => `<text x="48" y="${r.y}" font-family="DejaVu Sans, sans-serif" font-size="${r.size}" font-weight="${r.weight}" fill="#1c2b2a">${r.text}</text>`).join("\n")}
  </svg>`;
  const pipeline = sharp({ create: { width, height, channels: 3, background: "#fdfcf7" } }).composite([
    { input: Buffer.from(svg), top: 0, left: 0 },
  ]);
  if (format === "jpeg") await pipeline.jpeg({ quality: 82 }).toFile(filePath);
  else await pipeline.png().toFile(filePath);
}

