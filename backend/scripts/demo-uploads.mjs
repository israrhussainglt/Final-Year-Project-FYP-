fs.mkdirSync(OUT_DIR, { recursive: true });
console.log(`Generating mixed-format reports for ${PATIENTS.length} random patients…\n`);

for (const p of PATIENTS) {
  const slug = p.fullName.toLowerCase().replace(/\s+/g, "-");
  const dir = path.join(OUT_DIR, slug);
  fs.mkdirSync(dir, { recursive: true });
  p.files = p.files.map((f) => {
    const filePath = path.join(dir, f);
    if (f.endsWith(".pdf")) {
      const sections = (PDF_CONTENT[f] || (() => [["Summary", "Synthetic demo content."]]))(p.fullName);
      p.filesMeta ??= {};
      return { name: f, path: filePath, mime: "application/pdf", sections };
    }
    return { name: f, path: filePath, mime: f.endsWith(".png") ? "image/png" : "image/jpeg" };
  });

  for (const file of p.files) {
    if (file.mime === "application/pdf") {
      await generateTextPdf(file.path, file.name.replace(/\.pdf$/, "").replace(/-/g, " ").toUpperCase(), p.fullName, file.sections);
    } else {
      await generateScanImage(file.path, IMAGE_TITLES[file.name] || "Medical Report Scan", p.fullName, file.mime === "image/png" ? "png" : "jpeg");
    }
    ok(fs.existsSync(file.path) && fs.statSync(file.path).size > 200, `generated ${p.fullName}/${file.name} (${(fs.statSync(file.path).size / 1024).toFixed(1)} KB)`);
  }
}

